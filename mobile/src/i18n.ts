export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let str = I18N[lang]?.[key] ?? I18N.en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, String(v));
    });
  }
  return str;
}

